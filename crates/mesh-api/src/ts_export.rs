//! `export_bindings_*` companions of the ts-rs tests (feature `ts-export`, run by
//! `cargo xtask gen-ts`). ts-rs writes one `<Type>.ts` per exported type; this module
//! adds `constants.ts` (API version, key lists, enum values, GESTURE_COMMANDS, result
//! kinds) and the `index.ts` barrel, all derived from the Rust definitions.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

