/// Header of the files written here (the ts-rs files carry their own).
const NOTE: &str = "// This file was generated by `cargo xtask gen-ts` from crates/mesh-api. \
                    Do not edit this file manually.\n";

/// A string enum: TS name, values, exporter.
struct EnumInfo {
    name: &'static str,
    const_name: &'static str,
    values: Vec<&'static str>,
}

macro_rules! enums {
    ($( $ty:ident => $const_name:literal ),+ $(,)?) => {
        vec![$( EnumInfo {
            name: stringify!($ty),
            const_name: $const_name,
            values: $ty::ALL.iter().map(|v| v.as_str()).collect(),
        } ),+]
    };
}

