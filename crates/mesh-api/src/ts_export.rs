fn config() -> Config {
    Config::from_env()
}

/// Exports every root type (and, transitively, every dependency).
fn export_roots(cfg: &Config) {
    let results = [
        UiCommand::export_all(cfg),
        UiEvent::export_all(cfg),
        CommandResult::export_all(cfg),
        Snapshot::export_all(cfg),
        ParamValue::export_all(cfg),
    ];
    for r in results {
        r.expect("ts-rs export");
    }
    // String enums that no root references (key lists, discriminant sets).
    for r in [
        CommandType::export_all(cfg),
        EventType::export_all(cfg),
        ResultKind::export_all(cfg),
        PromptKey::export_all(cfg),
    ] {
        r.expect("ts-rs export");
    }
}

fn json<T: serde::Serialize + ?Sized>(v: &T) -> String {
    serde_json::to_string(v).expect("constants serialize")
}

/// The body of `constants.ts`.
pub(crate) fn constants_ts() -> String {
    let enums = string_enums();
    let mut out = String::from(NOTE);
    for e in &enums {
        let _ = writeln!(
            out,
            "import type {{ {0} }} from \"./{0}{1}\";",
            e.name,
            ext()
        );
    }
    out.push('\n');
    let _ = writeln!(out, "/** UI API version (DESIGN §3.7, Appendix A). */");
    let _ = writeln!(
        out,
        "export const API_VERSION = {} as const;",
        json(API_VERSION)
    );
    let _ = writeln!(
        out,
        "export const API_VERSION_MAJOR = {API_VERSION_MAJOR} as const;"
    );
    let _ = writeln!(
        out,
        "export const API_VERSION_MINOR = {API_VERSION_MINOR} as const;"
    );
    let _ = writeln!(out, "/** Invite QR auto-hide delay, ms. */");
    let _ = writeln!(
        out,
        "export const QR_HIDE_AFTER_MS = {QR_HIDE_AFTER_MS} as const;"
    );
    let _ = writeln!(out, "/** Display-name limit, UTF-8 bytes. */");
    let _ = writeln!(
        out,
        "export const DISPLAY_NAME_MAX_BYTES = {DISPLAY_NAME_MAX_BYTES} as const;\n"
    );
    for e in &enums {
        let _ = writeln!(
            out,
            "/** Every `{}` value, in Rust declaration order. */",
            e.name
        );
        let _ = writeln!(
            out,
            "export const {} = {} as const satisfies readonly {}[];",
            e.const_name,
            json(&e.values),
            e.name
        );
    }
    out.push_str("\n/** Every string-enum value set, by TS type name (used by the guards). */\n");
    out.push_str("export const ENUM_VALUES = {\n");
    for e in &enums {
        let _ = writeln!(out, "  {}: {},", e.name, e.const_name);
    }
    out.push_str("} as const;\n\n");

    let kinds: Vec<(&str, &str)> = CommandType::ALL
        .iter()
        .map(|t| (t.as_str(), t.result_kind().as_str()))
        .collect();
    out.push_str("/** Payload kind of a successful result, per command type. */\n");
    out.push_str("export const COMMAND_RESULT_KINDS = {\n");
    for (t, k) in kinds {
        let _ = writeln!(out, "  {t}: {},", json(k));
    }
    out.push_str("} as const satisfies Record<CommandType, ResultKind>;\n\n");

    let lab_cmds: Vec<_> = CommandType::ALL
        .iter()
        .filter(|t| t.in_lab_subset())
        .map(|t| t.as_str())
        .collect();
    let lab_events: Vec<_> = EventType::ALL
        .iter()
        .filter(|t| t.in_lab_subset())
        .map(|t| t.as_str())
        .collect();
    out.push_str("/** Phase 0 Lab subset of API 1.1 (frozen at Phase 0 exit). */\n");
    let _ = writeln!(
        out,
        "export const LAB_SUBSET_COMMAND_TYPES = {} as const satisfies readonly CommandType[];",
        json(&lab_cmds)
    );
    let _ = writeln!(
        out,
        "export const LAB_SUBSET_EVENT_TYPES = {} as const satisfies readonly EventType[];\n",
        json(&lab_events)
    );

    out.push_str(
        "/** ★ capture-gated commands (DESIGN §3.2): only through the plugin's \
         `gestureCommand`;\n *  `send` rejects them with `useGestureCommand`. `when: null` = \
         always gated. */\n",
    );
    out.push_str("export const GESTURE_COMMANDS = [\n");
    for rule in GESTURE_COMMANDS {
        let _ = writeln!(out, "  {},", json(rule));
    }
    out.push_str("] as const;\n");
    out
}

/// Import extension configured for ts-rs (`TS_RS_IMPORT_EXTENSION`), with the dot.
fn ext() -> String {
    config()
        .import_extension()
        .map(|e| format!(".{e}"))
        .unwrap_or_default()
}

/// Generated `<Type>.ts` names in `dir` (excluding this module's files), sorted.
fn generated_types(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .expect("export dir")
        .filter_map(|e| e.ok())
        .filter_map(|e| e.file_name().into_string().ok())
        .filter_map(|n| n.strip_suffix(".ts").map(str::to_owned))
        .filter(|n| n != "index" && n != "constants")
        .collect();
    names.sort();
    names
}

/// The body of `index.ts`.
fn index_ts(types: &[String]) -> String {
    let mut out = String::from(NOTE);
    for t in types {
        let _ = writeln!(out, "export type {{ {t} }} from \"./{t}{}\";", ext());
    }
    let _ = writeln!(out, "export * from \"./constants{}\";", ext());
    out
}

fn out_dir(cfg: &Config) -> PathBuf {
    cfg.out_dir().to_path_buf()
}

#[test]
fn export_bindings_constants_and_index() {
    let cfg = config();
    export_roots(&cfg);
    let dir = out_dir(&cfg);
    std::fs::write(dir.join("constants.ts"), constants_ts()).expect("write constants.ts");
    let types = generated_types(&dir);
    // Every string enum has its own file, so every key list can be imported.
    for e in string_enums() {
        assert!(types.iter().any(|t| t == e.name), "{} not exported", e.name);
    }
    for root in [
        "UiCommand",
        "UiEvent",
        "CommandResult",
        "Snapshot",
        "ParamValue",
    ] {
        assert!(types.iter().any(|t| t == root), "{root} not exported");
    }
    std::fs::write(dir.join("index.ts"), index_ts(&types)).expect("write index.ts");
}

#[test]
fn export_bindings_events_carry_no_free_text_fields() {
    // Every `string` field of an event type must be an id, a name (user content), a
    // path or a key: list them so a new free-text field cannot slip in unnoticed.
    let cfg = config();
    let decl = UiEvent::decl(&cfg);
    for forbidden in ["message", "text", "title", "description", "detail", "body"] {
        assert!(
            !decl.contains(&format!("{forbidden}:")),
            "UiEvent has `{forbidden}`"
        );
    }
    assert!(decl.contains("key: NoticeKey"));
    assert!(decl.contains("code: ErrorCode"));
}
