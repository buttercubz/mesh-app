import Foundation
import Synchronization

/// One stored Lab run file.
public struct LabRunFile: Sendable, Equatable {
    public var runId: String
    public var url: URL
    public var bytes: Int
    public var modified: Date
    /// `<runId>-summary.csv` next to it, when written.
    public var summaryURL: URL?
}

public enum LabFileStoreError: Error, Equatable, Sendable {
    case badRunId(String)
    case io(String)
}

/// Lab run files (`labrun/1` JSON Lines, contract C7; DESIGN §12.3): one file per device
/// per run under `Documents/lab/` (visible in Files), exported only through the share
/// sheet. `lab_write(run_id, line)` appends one line; handles stay open while a run writes.
public final class LabFileStore: Sendable {
    public let directory: URL
    private let handles = Mutex<[String: FileHandleBox]>([:])

    /// FileHandle is not Sendable; each box is only used under `handles`' lock.
    final class FileHandleBox: @unchecked Sendable {
        let handle: FileHandle
        init(_ h: FileHandle) { handle = h }
    }

    /// - Parameter directory: defaults to `Documents/lab`.
    public init(directory: URL? = nil) throws(LabFileStoreError) {
        let dir = directory ?? URL.documentsDirectory.appending(path: "lab", directoryHint: .isDirectory)
        do {
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        } catch {
            throw .io("create \(dir.lastPathComponent): \(error.localizedDescription)")
        }
        self.directory = dir
    }

    /// Run ids are generated by the core (`r-20261023-0912-ab12`); anything that could
    /// escape the directory is refused.
    public static func validate(_ runId: String) -> Bool {
        guard !runId.isEmpty, runId.count <= 96, !runId.hasPrefix(".") else { return false }
        return runId.unicodeScalars.allSatisfy {
            CharacterSet.alphanumerics.contains($0) && $0.isASCII || "-_.".unicodeScalars.contains($0)
        }
    }

    public func url(for runId: String) throws(LabFileStoreError) -> URL {
        guard Self.validate(runId) else { throw .badRunId(runId) }
        return directory.appending(path: "\(runId).jsonl", directoryHint: .notDirectory)
    }

    public func summaryURL(for runId: String) throws(LabFileStoreError) -> URL {
        guard Self.validate(runId) else { throw .badRunId(runId) }
        return directory.appending(path: "\(runId)-summary.csv", directoryHint: .notDirectory)
    }

    /// Appends one JSONL line (a trailing newline is added; embedded newlines refused).
    public func append(runId: String, line: String) throws(LabFileStoreError) {
        guard !line.contains("\n") else { throw .io("line contains a newline") }
        let target = try url(for: runId)
        let data = Data((line + "\n").utf8)
        let result: Result<Void, LabFileStoreError> = handles.withLock { hs in
            do {
                let box: FileHandleBox
                if let b = hs[runId] {
                    box = b
                } else {
                    if !FileManager.default.fileExists(atPath: target.path) {
                        FileManager.default.createFile(atPath: target.path, contents: nil)
                    }
                    box = FileHandleBox(try FileHandle(forWritingTo: target))
                    hs[runId] = box
                }
                try box.handle.seekToEnd()
                try box.handle.write(contentsOf: data)
                return .success(())
            } catch {
                return .failure(.io(error.localizedDescription))
            }
        }
        try result.get()
    }

    /// Closes the run's handle (run finished).
    public func finish(runId: String) {
        let box = handles.withLock { $0.removeValue(forKey: runId) }
        try? box?.handle.close()
    }

    public func writeSummary(runId: String, csv: String) throws(LabFileStoreError) {
        let u = try summaryURL(for: runId)
        do {
            try Data(csv.utf8).write(to: u, options: .atomic)
        } catch {
            throw .io(error.localizedDescription)
        }
    }

    public func lines(runId: String) throws(LabFileStoreError) -> [String] {
        let u = try url(for: runId)
        guard let d = FileManager.default.contents(atPath: u.path) else { return [] }
        return String(decoding: d, as: UTF8.self).split(separator: "\n", omittingEmptySubsequences: true)
            .map(String.init)
    }

    /// Stored runs, newest first.
    public func list() -> [LabRunFile] {
        let keys: Set<URLResourceKey> = [.fileSizeKey, .contentModificationDateKey]
        let urls = (try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: Array(keys))) ?? []
        return urls.filter { $0.pathExtension == "jsonl" }.compactMap { u -> LabRunFile? in
            let id = u.deletingPathExtension().lastPathComponent
            guard Self.validate(id) else { return nil }
            let v = try? u.resourceValues(forKeys: keys)
            let s = directory.appending(path: "\(id)-summary.csv", directoryHint: .notDirectory)
            return LabRunFile(runId: id, url: u, bytes: v?.fileSize ?? 0,
                              modified: v?.contentModificationDate ?? .distantPast,
                              summaryURL: FileManager.default.fileExists(atPath: s.path) ? s : nil)
        }.sorted { ($0.modified, $0.runId) > ($1.modified, $1.runId) }
    }

    /// Deletes a run and its summary.
    public func delete(runId: String) throws(LabFileStoreError) {
        finish(runId: runId)
        for u in [try url(for: runId), try summaryURL(for: runId)]
        where FileManager.default.fileExists(atPath: u.path) {
            do { try FileManager.default.removeItem(at: u) } catch { throw .io(error.localizedDescription) }
        }
    }

    /// Files to hand to the share sheet for a run (JSONL first, then the summary).
    public func exportURLs(runId: String) throws(LabFileStoreError) -> [URL] {
        let main = try url(for: runId)
        guard FileManager.default.fileExists(atPath: main.path) else { return [] }
        let s = try summaryURL(for: runId)
        return FileManager.default.fileExists(atPath: s.path) ? [main, s] : [main]
    }
}
