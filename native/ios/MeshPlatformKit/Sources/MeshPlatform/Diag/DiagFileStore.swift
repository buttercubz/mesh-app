import Foundation
import Synchronization

/// One diagnostics session on disk (`diag/<sessionId>/seg-NNNN.jsonl`).
public struct DiagSessionInfo: Sendable, Equatable {
    public var sessionId: String
    public var segments: [URL]
    public var bytes: Int
    public var modified: Date

    public init(sessionId: String, segments: [URL], bytes: Int, modified: Date) {
        self.sessionId = sessionId
        self.segments = segments
        self.bytes = bytes
        self.modified = modified
    }
}

/// Disk usage for the Settings line ("12.4 MB · 7 sessions · oldest 3 days ago").
public struct DiagUsage: Sendable, Equatable {
    public var bytes: Int
    public var sessions: Int
    public var oldest: Date?

    public init(bytes: Int, sessions: Int, oldest: Date?) {
        self.bytes = bytes
        self.sessions = sessions
        self.oldest = oldest
    }
}

public enum DiagFileStoreError: Error, Equatable, Sendable {
    case badSessionId(String)
    case badSegment(UInt32)
    case io(String)
}

/// The diagnostics flight recorder's files (`ridelog/1`, diagnostics spec §3.2, §5):
/// segments the runtime hands over through `PlatformHooks.diag_write`, kept in
/// `Application Support/diag` (app-private, not in the Files app, excluded from
/// backup). Budget: 64 MiB in total, oldest sessions evicted first; the current session
/// is never evicted (its oldest segments are, beyond 48 MiB); 14 days retention. Files
/// leave the device only through an explicit export (`exportZip`).
///
/// Privacy: the store never adds content; the runtime's redaction filter already ran.
/// Every segment file starts with its `hdr` line: lines for a segment whose file does not
/// exist (cleared or evicted mid-segment) are dropped until the next segment starts.
public final class DiagFileStore: Sendable {
    public static let defaultMaxBytes = 64 << 20
    public static let defaultCurrentMaxBytes = 48 << 20
    public static let defaultRetention: TimeInterval = 14 * 86_400

    public let directory: URL
    private let maxBytes: Int
    private let currentMaxBytes: Int
    private let retention: TimeInterval
    private let now: @Sendable () -> Date
    private let state = Mutex(State())

    struct State {
        var current: String?
        var open: (key: String, handle: HandleBox)?
        var bytesSinceBudget = 0
        var dropped = 0
    }

    /// FileHandle is not Sendable; the box is only used under `state`'s lock.
    final class HandleBox: @unchecked Sendable {
        let handle: FileHandle
        init(_ h: FileHandle) { handle = h }
    }

    /// - Parameter directory: defaults to `Application Support/diag`.
    public init(directory: URL? = nil, maxBytes: Int = defaultMaxBytes,
                currentMaxBytes: Int = defaultCurrentMaxBytes, retention: TimeInterval = defaultRetention,
                now: @escaping @Sendable () -> Date = { Date() }) throws(DiagFileStoreError) {
        let dir = directory ?? URL.applicationSupportDirectory.appending(path: "diag", directoryHint: .isDirectory)
        do {
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            var url = dir
            var values = URLResourceValues()
            values.isExcludedFromBackup = true
            try url.setResourceValues(values)
        } catch {
            throw .io("create \(dir.lastPathComponent): \(error.localizedDescription)")
        }
        self.directory = dir
        self.maxBytes = maxBytes
        self.currentMaxBytes = currentMaxBytes
        self.retention = retention
        self.now = now
        enforceBudget()
    }

    /// `d-YYYYMMDD-HHMM-xxxx` (generated by the runtime); anything else is refused.
    public static func validate(sessionId: String) -> Bool {
        sessionId.wholeMatch(of: /d-[0-9]{8}-[0-9]{4}-[0-9a-z]{4}/) != nil
    }

    public func sessionDirectory(_ id: String) throws(DiagFileStoreError) -> URL {
        guard Self.validate(sessionId: id) else { throw .badSessionId(id) }
        return directory.appending(path: id, directoryHint: .isDirectory)
    }

    public func segmentURL(sessionId: String, seg: UInt32) throws(DiagFileStoreError) -> URL {
        guard (1...9999).contains(seg) else { throw .badSegment(seg) }
        let name = "seg-" + String(format: "%04u", seg) + ".jsonl"
        return try sessionDirectory(sessionId).appending(path: name, directoryHint: .notDirectory)
    }

    /// Lines dropped because their segment file was gone (cleared / evicted).
    public var droppedLines: Int { state.withLock { $0.dropped } }

    /// Appends a `diag_write` batch. Lines must not contain newlines.
    public func append(sessionId: String, seg: UInt32, lines: [String]) throws(DiagFileStoreError) {
        guard !lines.isEmpty else { return }
        guard lines.allSatisfy({ !$0.contains("\n") }) else { throw .io("line contains a newline") }
        let target = try segmentURL(sessionId: sessionId, seg: seg)
        let key = "\(sessionId)/\(seg)"
        let data = Data((lines.joined(separator: "\n") + "\n").utf8)
        let result: Result<Bool, DiagFileStoreError> = state.withLock { st in
            do {
                st.current = sessionId
                let box: HandleBox
                if let open = st.open, open.key == key, FileManager.default.fileExists(atPath: target.path) {
                    box = open.handle
                } else {
                    try? st.open?.handle.handle.close()
                    st.open = nil
                    if !FileManager.default.fileExists(atPath: target.path) {
                        guard lines[0].hasPrefix(#"{"t":"hdr""#) else {
                            st.dropped += lines.count
                            return .success(false)
                        }
                        try FileManager.default.createDirectory(
                            at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
                        FileManager.default.createFile(atPath: target.path, contents: nil)
                    }
                    box = HandleBox(try FileHandle(forWritingTo: target))
                    st.open = (key, box)
                }
                try box.handle.seekToEnd()
                try box.handle.write(contentsOf: data)
                st.bytesSinceBudget += data.count
                let check = st.bytesSinceBudget >= 1 << 20
                if check { st.bytesSinceBudget = 0 }
                return .success(check)
            } catch {
                return .failure(.io(error.localizedDescription))
            }
        }
        if try result.get() { enforceBudget() }
    }

    /// Stored sessions, newest first.
    public func sessions() -> [DiagSessionInfo] {
        let fm = FileManager.default
        let dirs = (try? fm.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? []
        let keys: Set<URLResourceKey> = [.fileSizeKey, .contentModificationDateKey]
        return dirs.compactMap { d -> DiagSessionInfo? in
            let id = d.lastPathComponent
            guard Self.validate(sessionId: id) else { return nil }
            let segs = ((try? fm.contentsOfDirectory(at: d, includingPropertiesForKeys: Array(keys))) ?? [])
                .filter { $0.lastPathComponent.hasPrefix("seg-") && $0.pathExtension == "jsonl" }
                .sorted { $0.lastPathComponent < $1.lastPathComponent }
            guard !segs.isEmpty else { return nil }
            var bytes = 0
            var modified = Date.distantPast
            for s in segs {
                let v = try? s.resourceValues(forKeys: keys)
                bytes += v?.fileSize ?? 0
                modified = max(modified, v?.contentModificationDate ?? .distantPast)
            }
            return DiagSessionInfo(sessionId: id, segments: segs, bytes: bytes, modified: modified)
        }.sorted { ($0.modified, $0.sessionId) > ($1.modified, $1.sessionId) }
    }

    public func usage() -> DiagUsage {
        let s = sessions()
        return DiagUsage(bytes: s.reduce(0) { $0 + $1.bytes }, sessions: s.count,
                         oldest: s.map(\.modified).min())
    }

    /// Retention, then the total budget (oldest sessions first, never the current one),
    /// then the current session's own cap (its oldest segments, never the last).
    public func enforceBudget() {
        let current = state.withLock { $0.current }
        var list = sessions()
        let cutoff = now().addingTimeInterval(-retention)
        for s in list where s.sessionId != current && s.modified < cutoff {
            remove(s.sessionId)
        }
        list = sessions()
        var total = list.reduce(0) { $0 + $1.bytes }
        for s in list.reversed() where total > maxBytes && s.sessionId != current {
            remove(s.sessionId)
            total -= s.bytes
        }
        if let cur = list.first(where: { $0.sessionId == current }), cur.bytes > currentMaxBytes {
            var bytes = cur.bytes
            for seg in cur.segments.dropLast() where bytes > currentMaxBytes {
                let size = (try? seg.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0
                try? FileManager.default.removeItem(at: seg)
                bytes -= size
            }
        }
    }

    private func remove(_ id: String) {
        guard let d = try? sessionDirectory(id) else { return }
        state.withLock { st in
            if st.open?.key.hasPrefix(id + "/") == true {
                try? st.open?.handle.handle.close()
                st.open = nil
            }
        }
        try? FileManager.default.removeItem(at: d)
    }

    /// Deletes every diagnostics file (the toggle and the RAM ring are unaffected).
    public func clear() {
        state.withLock { st in
            try? st.open?.handle.handle.close()
            st.open = nil
        }
        for s in sessions() { remove(s.sessionId) }
    }

    /// Scope of an export.
    public enum ExportScope: String, Sendable {
        /// The most recent session (all its segments).
        case last
        /// Every stored session.
        case all
    }

    /// Writes `convlink-diag-<label>.zip` into `outDir` with the chosen sessions and
    /// `device.json`. When no session file exists, `ring` (the runtime's RAM ring, a
    /// self-contained JSONL file) is exported as `diag/ring.jsonl`. Returns the zip URL
    /// and the number of sessions in it.
    public func exportZip(scope: ExportScope, label: String, deviceJSON: String, ring: [String]?,
                          outDir: URL) throws(DiagFileStoreError) -> (url: URL, sessions: Int) {
        let all = sessions()
        let chosen = scope == .last ? Array(all.prefix(1)) : all
        var entries: [DiagZip.Entry] = [DiagZip.Entry(name: "device.json", data: Data(deviceJSON.utf8))]
        for s in chosen {
            for seg in s.segments {
                guard let d = FileManager.default.contents(atPath: seg.path) else { continue }
                entries.append(DiagZip.Entry(name: "diag/\(s.sessionId)/\(seg.lastPathComponent)", data: d))
            }
        }
        if chosen.isEmpty, let ring, !ring.isEmpty {
            entries.append(DiagZip.Entry(name: "diag/ring.jsonl", data: Data((ring.joined(separator: "\n") + "\n").utf8)))
        }
        let safe = String(label.unicodeScalars.filter {
            CharacterSet.alphanumerics.contains($0) && $0.isASCII || "-_".unicodeScalars.contains($0)
        }.map(Character.init).prefix(80))
        let url = outDir.appending(path: "convlink-diag-\(safe.isEmpty ? "export" : safe).zip", directoryHint: .notDirectory)
        do {
            try FileManager.default.createDirectory(at: outDir, withIntermediateDirectories: true)
            try DiagZip.archive(entries).write(to: url, options: .atomic)
        } catch {
            throw .io(error.localizedDescription)
        }
        return (url, chosen.count)
    }
}
