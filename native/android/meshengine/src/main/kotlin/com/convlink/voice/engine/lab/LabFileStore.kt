package com.convlink.voice.engine.lab

import android.content.Context
import java.io.File
import java.io.FileOutputStream
import java.io.IOException

/** One stored Lab run file. */
data class LabRunFile(val runId: String, val file: File, val bytes: Long, val modifiedMs: Long, val summary: File?)

/**
 * Lab run files (`labrun/1` JSON Lines, contract C7; DESIGN §12.3): one file per device per
 * run, `<runId>.jsonl`, plus `<runId>-summary.csv`. `lab_write(run_id, line)` appends one
 * line; streams stay open while a run writes and every line is flushed. Exported only
 * through the app's share sheet (WP-19 FileProvider). Thread-safe.
 */
class LabFileStore(val directory: File) {
    private val streams = HashMap<String, FileOutputStream>()

    init {
        if (!directory.isDirectory && !directory.mkdirs()) throw IOException("cannot create $directory")
    }

    fun file(runId: String): File = File(directory, "${checked(runId)}.jsonl")

    fun summaryFile(runId: String): File = File(directory, "${checked(runId)}-summary.csv")

    /** Appends one JSONL line (a trailing newline is added; embedded newlines are refused). */
    @Synchronized
    fun append(runId: String, line: String) {
        require(!line.contains('\n')) { "line contains a newline" }
        val target = file(runId)
        val out = streams.getOrPut(runId) { FileOutputStream(target, true) }
        out.write((line + "\n").toByteArray(Charsets.UTF_8))
        out.flush()
    }

    /** Appends one line of the run's summary CSV (`lab_write_summary`). */
    @Synchronized
    fun appendSummary(runId: String, line: String) {
        require(!line.contains('\n')) { "line contains a newline" }
        summaryFile(runId).appendText(line + "\n", Charsets.UTF_8)
    }

    /** Closes the run's open stream (run finished). */
    @Synchronized
    fun close(runId: String) {
        streams.remove(runId)?.close()
    }

    @Synchronized
    fun closeAll() {
        streams.values.forEach { runCatching { it.close() } }
        streams.clear()
    }

    /** Deletes the run's files (`lab_delete`). */
    @Synchronized
    fun delete(runId: String) {
        close(runId)
        file(runId).delete()
        summaryFile(runId).delete()
    }

    /** Every run file, newest first. */
    @Synchronized
    fun list(): List<LabRunFile> = (directory.listFiles() ?: emptyArray())
        .filter { it.isFile && it.name.endsWith(".jsonl") }
        .map {
            val id = it.name.removeSuffix(".jsonl")
            val summary = File(directory, "$id-summary.csv").takeIf { s -> s.isFile }
            LabRunFile(id, it, it.length(), it.lastModified(), summary)
        }
        .sortedByDescending { it.modifiedMs }

    companion object {
        /** App-specific external storage (`Android/data/<app>/files/lab`), else internal files. */
        fun create(context: Context): LabFileStore {
            val base = context.getExternalFilesDir(null) ?: context.filesDir
            return LabFileStore(File(base, "lab"))
        }

        /** Run ids are generated by the core (`r-20261023-0912-ab12`); nothing may escape. */
        fun validate(runId: String): Boolean = runId.isNotEmpty() && runId.length <= 96 &&
            !runId.startsWith(".") && runId.all { it.isLetterOrDigit() && it.code < 128 || it in "-_." }

        private fun checked(runId: String): String {
            require(validate(runId)) { "bad run id: $runId" }
            return runId
        }
    }
}
